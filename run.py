#!/usr/bin/env python
"""Build script for the Quarter 1 project (DSC 180A, D25). Each target calls existing code in
src/ and scripts/; no target trains a model, calls a paid API or touches a sealed test set.

    python run.py test        # unit tests, then the offline pipeline on the 44-case test subset
    python run.py data        # regenerate every committed dataset in memory, compare hashes
    python run.py baselines   # zero-call baselines on benchmark_v3, scored -> build/baselines/
    python run.py reports     # rebuild results/phase2-6/RESULTS.md from the saved replies
    python run.py all         # data, baselines and reports
    python run.py clean       # delete build/ (committed data and results are never touched)
    python run.py demo        # local chat demo (Apple Silicon: MLX env, base model, adapters)

Targets can be combined, e.g. `python run.py data baselines`. Run with the project environment
(`.venv`, see README). Steps marked [mlx] need the Apple Silicon environment `.venv-mlx`
(docs/phase2_training.md); set MLX_PYTHON to point at another interpreter. Without it those
steps are skipped with a message, and everything else still runs.
"""

import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
BUILD = ROOT / "build"
PY = sys.executable
MLX = os.environ.get("MLX_PYTHON", str(ROOT / ".venv-mlx" / "bin" / "python"))
PILOT_IDS = "data/synthetic/benchmark_v3_pilot_ids.json"
BASELINES = ["copy_context", "heuristic_surface", "always_abstain", "always_answer"]


def step(args, mlx=False, path=None):
    """Run one command from the repository root; stop the build if it fails."""
    exe = MLX if mlx else PY
    shown = ("[mlx] " if mlx else "") + " ".join(str(a) for a in args)
    if mlx and not Path(exe).exists():
        print(f"-- skipped, needs the MLX environment: {shown}")
        return
    env = dict(os.environ)
    if path:
        env["PYTHONPATH"] = os.pathsep.join(path + [env.get("PYTHONPATH", "")]).rstrip(os.pathsep)
    print(f"$ {shown}", flush=True)
    if subprocess.run([exe, *args], cwd=ROOT, env=env).returncode != 0:
        sys.exit(f"run.py: step failed: {shown}")


CLI = "import sys; from bazireason.cli import main; sys.argv[0] = 'bazireason'; main()"


def cli(*args):
    """The project's command-line tool (`bazireason`, installed by requirements.txt)."""
    step(["-c", CLI, *args])


def fresh(folder):
    """Outputs are never overwritten by the tools, so each target starts from an empty folder."""
    shutil.rmtree(folder, ignore_errors=True)
    folder.mkdir(parents=True)
    return folder.relative_to(ROOT)


def data():
    """Every dataset is generated by seeded code; --check rebuilds it in memory and compares."""
    for version, path in [("benchmark_v3", "benchmark_v3.jsonl"), ("audit_v2", "audit_v2.jsonl"),
                          ("checkpoint_v1", "checkpoint.jsonl")]:  # fmt: skip
        cli("generate", "--dataset-version", version, "--check", f"data/synthetic/{path}")
    step(["scripts/phase2/build_dataset.py", "--check"], mlx=True)
    step(["scripts/phase2/build_dataset.py", "--dataset", "2", "--check"], mlx=True)
    for n in ("1", "2", "3"):
        step(
            ["scripts/phase3/build_dataset.py", *([] if n == "1" else ["--dataset", n]), "--check"]
        )
    step(["scripts/phase4/build_dataset.py", "--check"])
    step(["scripts/phase4/build_splits.py", "--check"])
    step(["scripts/phase5/build_eval.py", "--check"])
    step(["scripts/phase5/build_train.py", "--check"])
    step(["scripts/phase5/gen_blind.py", "--check"], mlx=True)
    step(["scripts/phase6/build_eval6.py", "--check"], path=["src"])


def baselines(out=None, subset=False):
    """Zero-call controls (no model): copy, surface heuristic, always abstain, always answer."""
    out = out or fresh(BUILD / "baselines")
    ids = ["--case-ids-file", PILOT_IDS] if subset else []
    cli(
        "run",
        *ids,
        "--methods",
        *BASELINES,
        "--max-calls",
        "0",
        "--output",
        f"{out}/baselines.jsonl",
    )
    cli(
        "evaluate",
        "--predictions",
        f"{out}/baselines.jsonl",
        "--output",
        f"{out}/baselines_scores.json",
    )


def reports():
    """Result reports are rebuilt from the saved replies in results/; no model is needed."""
    # Phase 2 draws its loss curves with matplotlib, which the MLX environment has (extra "mlx")
    step(["scripts/phase2/make_report.py"], mlx=True)
    step(["scripts/phase3/make_report.py"])
    step(["scripts/phase4/make_report.py"])
    step(["scripts/phase5/make_report5.py"])
    step(["scripts/phase6/make_report6.py"], path=["src", "scripts/phase6", "scripts/phase5"])


def test():
    """Unit tests, then the offline pipeline end to end on the 44-case pilot subset."""
    step(["-m", "pytest", "-q"])
    out = fresh(BUILD / "test")
    cli(
        "generate",
        "--dataset-version",
        "benchmark_v3",
        "--check",
        "data/synthetic/benchmark_v3.jsonl",
    )
    baselines(out, subset=True)
    # The model path end to end with a deterministic mock backend (no network, no weights)
    step(["scripts/run_pilot.py", "--backend", "mock", "--design", "combined", "--max-calls", "352",
          "--output", f"{out}/mock_pilot.jsonl"])  # fmt: skip
    print(f"test: passed; outputs in {out}/")


def demo():
    step(["-m", "bazireason.demo_app"], mlx=True)


def clean():
    shutil.rmtree(BUILD, ignore_errors=True)
    print("removed build/")


TARGETS = {"test": test, "data": data, "baselines": baselines, "reports": reports, "clean": clean,
           "demo": demo, "all": lambda: (data(), baselines(), reports())}  # fmt: skip

if __name__ == "__main__":
    targets = sys.argv[1:] or ["test"]
    unknown = [t for t in targets if t not in TARGETS]
    if unknown:
        sys.exit(f"unknown target(s): {', '.join(unknown)}; choose from {', '.join(TARGETS)}")
    for target in targets:
        print(f"== {target}", flush=True)
        TARGETS[target]()
